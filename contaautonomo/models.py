"""The core's database models (tables of invoices, customers, banks, settings,
contractors, expenses, tax forms, documents, Social Security payments,
messages). Modules mirror the ones they use with `extend_existing=True`.
`contaautonomo.app` re-exports them, so `from contaautonomo.app import Invoice`
keeps working."""

from contaautonomo.extensions import db
